import { config as loadEnv } from "dotenv";
import { readFileSync, writeFileSync } from "node:fs";
loadEnv({ path: [".env.local"], quiet: true });

/**
 * Point the LOCAL Supabase auth service at a real SMTP account so magic links
 * reach a real inbox instead of Mailpit. Reads SMTP_* from .env.local and
 * writes an [auth.email.smtp] block into supabase/config.toml, then you restart
 * the stack. Run with no SMTP_* set to switch back to Mailpit.
 *
 *   pnpm mail:local && pnpm supabase:restart
 */
const path = "supabase/config.toml";
const toml = readFileSync(path, "utf8");
const start = toml.indexOf("# --- local-smtp:start");
const end = toml.indexOf("# --- local-smtp:end");
const base = start >= 0 && end >= 0 ? toml.slice(0, start) + toml.slice(end + "# --- local-smtp:end".length).replace(/^\n/, "") : toml;

const host = process.env.SMTP_HOST;
const user = process.env.SMTP_USER;
const pass = process.env.SMTP_PASS;
const port = process.env.SMTP_PORT ?? "587";
const sender = process.env.SMTP_SENDER ?? user;
const senderName = process.env.SMTP_SENDER_NAME ?? "Job Journey";

let out = base.trimEnd() + "\n";
if (host && user && pass) {
  out += `
# --- local-smtp:start (generated by scripts/local-smtp.ts; values come from .env.local)
[auth.email.smtp]
enabled = true
host = "env(SMTP_HOST)"
port = ${Number(port)}
user = "env(SMTP_USER)"
pass = "env(SMTP_PASS)"
admin_email = "${sender}"
sender_name = "${senderName}"
# --- local-smtp:end
`;
  console.log(`SMTP enabled via ${host}:${port} as ${user}; sender ${senderName} <${sender}>.`);
  console.log("Now run: pnpm supabase:restart");
} else {
  console.log("No SMTP_HOST/SMTP_USER/SMTP_PASS in .env.local; local mail stays in Mailpit (http://127.0.0.1:54324).");
}
writeFileSync(path, out);
